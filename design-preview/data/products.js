//   source        returned | open_box | surplus | liquidation (source_type)
//   grade         new | A | B | C | D | R | F        (condition_grade)
//   currentBid, startingBid, increment, bidCount, bidderCount, watchers
//   price / originalPrice (final_price / original_price), stock
//   buyNowPrice (for "both"), marketPrice (average_market_price)
//   fullStockRequired (full_stock_required)
//
// Times are relative so countdowns are always meaningful:
//   endsIn / startsIn are seconds from page load; listedHoursAgo drives "New".
