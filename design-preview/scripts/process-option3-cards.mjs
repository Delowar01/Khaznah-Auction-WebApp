#!/usr/bin/env node
// WebP derivatives of the approved Option 3 hero card artwork (Auction, Buy
// Now, Live Auction; English and Arabic).
//
//   node scripts/process-option3-cards.mjs
//
// Reads the masters in assets-src/option3-cards/ (byte-identical copies of
// the supplied files; checked against the SHA-256 in its ASSET_MANIFEST.json),
// writes WebP files to public/images/work/option3-cards/ and the
// source-to-derivative table to assets-src/option3-cards/DERIVATIVES.md.
// The pictures carry their own words, so they are encoded at a higher
// quality than the Priority 1 and 2 photographs (no visible change to the
// lettering or colours at 3× zoom), only ever downscaled and never cropped:
// the widest file of each card is the master at its own size.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SRC = path.resolve("assets-src/option3-cards");
const OUT = path.resolve("public/images/work/option3-cards");
const manifest = JSON.parse(fs.readFileSync(path.join(SRC, "ASSET_MANIFEST.json"), "utf8"));

const WEBP = { quality: 92, effort: 6, smartSubsample: true };
// Widths cover each card's largest painted size at 2× (the square Auction
// card is at most ≈650 px wide, the wide cards ≈510 px).
const WIDTHS = { auction: [640, 960], "buy-now": [640, 960, 1280], "live-auction": [640, 960, 1280] };

fs.mkdirSync(OUT, { recursive: true });
const sha256 = (buf) => crypto.createHash("sha256").update(buf).digest("hex");
const rows = [];

for (const entry of manifest.assets) {
  const buf = fs.readFileSync(path.join(SRC, entry.filename));
  const actual = sha256(buf);
  if (actual !== entry.sha256) throw new Error(`${entry.filename}: SHA-256 ${actual} does not match the manifest (${entry.sha256})`);
  const base = sharp(buf);
  const { width, height } = await base.metadata();
  if (width !== entry.width || height !== entry.height) throw new Error(`${entry.filename}: ${width}×${height}, the manifest says ${entry.width}×${entry.height}`);
  const name = entry.filename.replace(/\.png$/, "");
  for (const w of [...WIDTHS[entry.card], width]) {
    if (w > width) throw new Error(`${name}: ${w}px would upscale a ${width}px source`);
    const h = Math.round((w * height) / width);
    const out = `${name}-${w}.webp`;
    const pipeline = w === width ? base.clone() : base.clone().resize({ width: w, height: h, kernel: "lanczos3" });
    await pipeline.webp(WEBP).toFile(path.join(OUT, out));
    const bytes = fs.statSync(path.join(OUT, out)).size;
    rows.push({ source: entry.filename, sourceSize: `${width} × ${height}`, out, size: `${w} × ${h}`, bytes });
    console.log(`${entry.filename} → ${out}  ${w}×${h}  ${(bytes / 1024).toFixed(1)} KB`);
  }
}

const table = [
  "# Option 3 hero cards — source to derivative mapping",
  "",
  "Approved final artwork for the Option 3 home hero cards (Auction, Buy Now, Live Auction; English and",
  "Arabic), used exactly as supplied. Generated by `scripts/process-option3-cards.mjs` from the masters in",
  "this folder (byte-identical to the supplied files listed in `ASSET_MANIFEST.json`, SHA-256 checked).",
  "Served from `public/images/work/option3-cards/`. Nothing is upscaled or cropped; the widest file of",
  "each card is the master at its own size.",
  "",
  "| Source (master) | Master px | Derivative | Px | Bytes |",
  "|---|---|---|---|---|",
  ...rows.map((r) => `| \`${r.source}\` | ${r.sourceSize} | \`${r.out}\` | ${r.size} | ${r.bytes.toLocaleString("en-US")} |`),
  "",
  `WebP settings: quality ${WEBP.quality}, effort ${WEBP.effort}, smart subsampling (the lettering is part of the picture).`,
  "",
];
fs.writeFileSync(path.join(SRC, "DERIVATIVES.md"), table.join("\n"));
console.log(`\n${rows.length} derivatives written to ${path.relative(process.cwd(), OUT)}/`);
