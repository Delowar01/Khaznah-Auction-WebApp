#!/usr/bin/env node
// WebP derivatives of the Priority 2 dummy / preview photography (B1–B18).
//
//   node scripts/process-priority-2-assets.mjs
//
// Reads the masters in assets-src/priority-2/ (byte-identical copies of the
// KHAZNAH_PRIORITY_2_ASSETS package; checked against the SHA-256 in its
// PRIORITY_2_ASSET_MANIFEST.json), writes WebP files to
// public/images/work/priority-2/ and the source-to-derivative table to
// assets-src/priority-2/DERIVATIVES.md. Same approach as Priority 1
// (scripts/process-work-assets.mjs): derivatives are only ever downscaled and
// the widest file of each asset is the master at its own size. The B1–B4
// cut-outs keep their alpha channel (lossless alpha) and are not trimmed:
// their ~2 % transparent margin is part of the delivered asset.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SRC = path.resolve("assets-src/priority-2");
const OUT = path.resolve("public/images/work/priority-2");
const manifest = JSON.parse(fs.readFileSync(path.join(SRC, "PRIORITY_2_ASSET_MANIFEST.json"), "utf8"));

const PHOTO = { quality: 82, effort: 6, smartSubsample: true };
const CUTOUT = { quality: 88, alphaQuality: 100, effort: 6 };

// Widths cover each slot's largest rendered size at 2× (object-fit: cover
// draws a wide master wider than its box, so the seller and hero sets start
// at the width their narrowest crop actually paints).
const ASSETS = [
  { id: "B1", widths: [300, 600, 900], webp: CUTOUT },
  { id: "B2", widths: [300, 600, 900], webp: CUTOUT },
  { id: "B3", widths: [240, 480], webp: CUTOUT },
  { id: "B4", widths: [240, 480], webp: CUTOUT },
  { id: "B5", widths: [832, 1248] },
  { id: "B6", widths: [768, 1152] },
  { id: "B7a", widths: [400, 700] },
  { id: "B7b", widths: [400, 700, 1000] },
  { id: "B7c", widths: [400, 700, 1000] },
  { id: "B7d", widths: [400, 700, 1000] },
  { id: "B7e", widths: [400, 700, 1000] },
  { id: "B7f", widths: [400, 700] },
  { id: "B8a", widths: [480, 880, 1320] },
  { id: "B8b", widths: [480, 880, 1320] },
  { id: "B8c", widths: [480, 880, 1320] },
  { id: "B9", widths: [640, 960, 1280] },
  { id: "B10", widths: [640, 960, 1280] },
  { id: "B11", widths: [240, 480] },
  { id: "B12", widths: [480, 960] },
  { id: "B13", widths: [800, 1440] },
  { id: "B14", widths: [800, 1440] },
  { id: "B15", widths: [800, 1440] },
  { id: "B16", widths: [240, 480] },
  { id: "B17", widths: [660, 1320] },
  { id: "B18", widths: [800, 1440] },
];

/** "B7a_kz-o3-wall-suede-tote-v1.png" → "b7a-o3-wall-suede-tote" */
const derivativeName = (id, file) => `${id.toLowerCase()}-${file.replace(/^B\d+[a-f]?_kz-/, "").replace(/-v\d+\.png$/, "")}`;

fs.mkdirSync(OUT, { recursive: true });
const sha256 = (buf) => crypto.createHash("sha256").update(buf).digest("hex");
const rows = [];

for (const asset of ASSETS) {
  const entry = manifest.assets.find((a) => a.b_id === asset.id);
  if (!entry) throw new Error(`${asset.id}: not in PRIORITY_2_ASSET_MANIFEST.json`);
  const buf = fs.readFileSync(path.join(SRC, entry.filename));
  const actual = sha256(buf);
  if (actual !== entry.sha256) throw new Error(`${entry.filename}: SHA-256 ${actual} does not match the manifest (${entry.sha256})`);

  const base = sharp(buf);
  const { width, height, hasAlpha } = await base.metadata();
  if (entry.transparency !== hasAlpha) throw new Error(`${entry.filename}: alpha channel does not match the manifest`);
  const name = derivativeName(asset.id, entry.filename);
  const webp = asset.webp ?? PHOTO;
  for (const w of [...asset.widths, width]) {
    if (w > width) throw new Error(`${name}: ${w}px would upscale a ${width}px source`);
    const h = Math.round((w * height) / width);
    const out = `${name}-${w}.webp`;
    const pipeline = w === width ? base.clone() : base.clone().resize({ width: w, height: h, kernel: "lanczos3" });
    await pipeline.webp(webp).toFile(path.join(OUT, out));
    const bytes = fs.statSync(path.join(OUT, out)).size;
    rows.push({ id: asset.id, source: entry.filename, sourceSize: `${width} × ${height}`, out, size: `${w} × ${h}`, bytes, alpha: hasAlpha });
    console.log(`${asset.id} → ${out}  ${w}×${h}  ${(bytes / 1024).toFixed(1)} KB`);
  }
}

const table = [
  "# Priority 2 assets — source to derivative mapping",
  "",
  "Temporary dummy / preview imagery for the Options 2–4 home pages only.",
  "Generated by `scripts/process-priority-2-assets.mjs` from the masters in this folder",
  "(byte-identical to `KHAZNAH_PRIORITY_2_ASSETS_part_1.zip` and `_part_2.zip`; SHA-256 checked against",
  "`PRIORITY_2_ASSET_MANIFEST.json`). Served from `public/images/work/priority-2/`. Nothing is upscaled;",
  "the widest file of each asset is the master at its own size.",
  "",
  "| ID | Source (master) | Master px | Derivative | Px | Bytes | Alpha |",
  "|---|---|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.id} | \`${r.source}\` | ${r.sourceSize} | \`${r.out}\` | ${r.size} | ${r.bytes.toLocaleString("en-US")} | ${r.alpha ? "yes" : "no"} |`),
  "",
  `WebP settings: photographs quality ${PHOTO.quality} (effort ${PHOTO.effort}, smart subsampling); B1–B4 cut-outs quality ${CUTOUT.quality} with lossless alpha (alphaQuality ${CUTOUT.alphaQuality}).`,
  "",
];
fs.writeFileSync(path.join(SRC, "DERIVATIVES.md"), table.join("\n"));
console.log(`\n${rows.length} derivatives written to ${path.relative(process.cwd(), OUT)}/`);
