#!/usr/bin/env node
// WebP derivatives of the approved Priority 1 photography (A1–A7).
//
//   node scripts/process-work-assets.mjs
//
// Reads the masters in assets-src/priority-1/ (byte-identical copies of the
// approved KHAZNAH_PRIORITY_1_FINAL package; checked against the SHA-256 in
// its ASSET_MANIFEST.json), writes WebP files to public/images/work/ and the
// source-to-derivative table to assets-src/priority-1/DERIVATIVES.md.
// Derivatives are only ever downscaled; the full-width file of each asset is
// the master at its own size. A2 keeps its alpha channel (lossless alpha) and
// is only trimmed to the bounds of its non-transparent pixels.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SRC = path.resolve("assets-src/priority-1");
const OUT = path.resolve("public/images/work");
const manifest = JSON.parse(fs.readFileSync(path.join(SRC, "ASSET_MANIFEST.json"), "utf8"));

const PHOTO = { quality: 82, effort: 6, smartSubsample: true };
const ASSETS = [
  { id: "A1", file: "A1_kz-shared-recliner-studio-v1.png", name: "a1-recliner-studio", widths: [400, 800, 1254], webp: { quality: 86, effort: 6 } },
  { id: "A2", file: "A2_kz-shared-recliner-cutout-v2.png", name: "a2-recliner-cutout", widths: [300, 600, 1108], webp: { quality: 88, alphaQuality: 100, effort: 6 }, trim: [66, 102, 1174, 1156] },
  { id: "A3", file: "A3_kz-o2-hero-room-ltr-v2.png", name: "a3-o2-hero-room-ltr", widths: [960, 1440, 1920, 2508], webp: PHOTO },
  { id: "A4", file: "A4_kz-o2-hero-room-rtl-v2.png", name: "a4-o2-hero-room-rtl", widths: [960, 1440, 1920, 2508], webp: PHOTO },
  { id: "A5", file: "A5_kz-o3-hero-furniture-v2.png", name: "a5-o3-hero-furniture", widths: [600, 900, 1200], webp: PHOTO },
  { id: "A6", file: "A6_kz-o4-hero-limestone-wide-v2.png", name: "a6-o4-hero-limestone-wide", widths: [960, 1440, 1920, 2508], webp: PHOTO },
  { id: "A7", file: "A7_kz-o4-hero-limestone-mobile-v1.png", name: "a7-o4-hero-limestone-mobile", widths: [496, 744, 992], webp: PHOTO },
];

fs.mkdirSync(OUT, { recursive: true });
const sha256 = (buf) => crypto.createHash("sha256").update(buf).digest("hex");
const rows = [];

for (const asset of ASSETS) {
  const buf = fs.readFileSync(path.join(SRC, asset.file));
  const expected = manifest.assets.find((a) => a.id === asset.id)?.sha256;
  const actual = sha256(buf);
  if (actual !== expected) throw new Error(`${asset.file}: SHA-256 ${actual} does not match the approved manifest (${expected})`);

  let base = sharp(buf);
  const meta = await base.metadata();
  let width = meta.width;
  let height = meta.height;
  if (asset.trim) {
    const [x0, y0, x1, y1] = asset.trim;
    base = sharp(await base.extract({ left: x0, top: y0, width: x1 - x0, height: y1 - y0 }).png().toBuffer());
    width = x1 - x0;
    height = y1 - y0;
  }
  for (const w of asset.widths) {
    if (w > width) throw new Error(`${asset.name}: ${w}px would upscale a ${width}px source`);
    const h = Math.round((w * height) / width);
    const out = `${asset.name}-${w}.webp`;
    const pipeline = w === width ? base.clone() : base.clone().resize({ width: w, height: h, kernel: "lanczos3" });
    await pipeline.webp(asset.webp).toFile(path.join(OUT, out));
    const bytes = fs.statSync(path.join(OUT, out)).size;
    rows.push({ id: asset.id, source: asset.file, sourceSize: `${meta.width} × ${meta.height}`, out, size: `${w} × ${h}`, bytes, note: asset.trim ? `trimmed to alpha bounds x ${asset.trim[0]}–${asset.trim[2]}, y ${asset.trim[1]}–${asset.trim[3]}` : "" });
    console.log(`${asset.id} → ${out}  ${w}×${h}  ${(bytes / 1024).toFixed(1)} KB`);
  }
}

const table = [
  "# Priority 1 assets — source to derivative mapping",
  "",
  "Generated by `scripts/process-work-assets.mjs` from the approved masters in this folder",
  "(byte-identical to `KHAZNAH_PRIORITY_1_FINAL.zip`; SHA-256 checked against `ASSET_MANIFEST.json`).",
  "Served from `public/images/work/`. Nothing is upscaled; the widest file of each asset is the master at its own size.",
  "",
  "| ID | Source (master) | Master px | Derivative | Px | Bytes | Note |",
  "|---|---|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.id} | \`${r.source}\` | ${r.sourceSize} | \`${r.out}\` | ${r.size} | ${r.bytes.toLocaleString("en-US")} | ${r.note} |`),
  "",
  `WebP settings: photographs quality ${PHOTO.quality} (effort ${PHOTO.effort}, smart subsampling); A1 quality 86; A2 quality 88 with lossless alpha.`,
  "",
];
fs.writeFileSync(path.join(SRC, "DERIVATIVES.md"), table.join("\n"));
console.log(`\n${rows.length} derivatives written to ${path.relative(process.cwd(), OUT)}/`);
